"""Builds the browser data files in web/data/ from the hackathon CSVs.

Usage:  python tools/build_data.py <folder with the CSVs>
Re-run whenever the source CSVs change.
"""
import json, sys, os, warnings
import numpy as np, pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
warnings.filterwarnings('ignore')

SRC = sys.argv[1] if len(sys.argv) > 1 else 'data'
OUT = os.path.join(os.path.dirname(__file__), '..', 'web', 'data')
os.makedirs(OUT, exist_ok=True)

def js(name, var, obj):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8') as f:
        f.write(f'// Generated by tools/build_data.py from the synthetic hackathon data. Do not edit.\n')
        f.write(f'window.{var} = ' + json.dumps(obj, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('wrote', name, os.path.getsize(os.path.join(OUT, name)) // 1024, 'KB')

def find(stem):
    for f in os.listdir(SRC):
        if f.endswith(stem): return os.path.join(SRC, f)
    raise FileNotFoundError(stem)

cat = pd.read_csv(find('product_catalogue.csv'))
gst = pd.read_csv(find('mock_gstin_registry.csv'))
udy = pd.read_csv(find('mock_udyam_registry.csv'))
leads = pd.read_csv(find('smb_leads.csv'))

# ---- catalogue
products = []
for r in cat.itertuples():
    products.append(dict(id=r.product_id, category=r.category, name=r.product_name, description=r.description, unit=r.unit,
        priceMin=int(r.price_min_inr_per_month), priceMax=int(r.price_max_inr_per_month), setup=int(r.one_time_setup_inr),
        minContract=int(r.min_contract_months), tiers=[int(t) for t in str(r.available_city_tiers).split(';')],
        minEmployees=int(r.min_employees), minSites=int(r.min_sites), requiresGstin=r.requires_gstin == 'Y',
        requiresOneOf=str(r.requires_one_of).split('|') if isinstance(r.requires_one_of, str) else [],
        installDays=int(r.typical_install_days), segments=str(r.target_segments).split(';')))
js('catalogue.js', 'CATALOGUE', products)

# ---- registries (compact arrays keep the files small)
js('gstin_registry.js', 'GSTIN_REGISTRY', {r.gstin: [r.legal_name, r.trade_name, r.constitution, r.principal_place_of_business, r.state, r.registration_date, r.status] for r in gst.itertuples()})
js('udyam_registry.js', 'UDYAM_REGISTRY', {r.udyam_number: [r.enterprise_name, r.enterprise_type, r.major_activity, r.nic_description, r.state, r.city, r.date_of_registration] for r in udy.itertuples()})

# ---- cities -> tier/state (used for availability checks)
cities = leads.groupby('city').agg(tier=('city_tier', 'first'), state=('state', 'first')).reset_index()
js('cities.js', 'CITIES', {r.city: [int(r.tier), r.state] for r in cities.itertuples()})

# ---- propensity model on attributes known when the lead is created
y = (leads.outcome == 'Activated').astype(int)
CATS = ['segment', 'lead_source', 'city_tier', 'preferred_language', 'annual_turnover_band', 'has_gstin', 'has_udyam', 'current_internet', 'current_provider', 'contact_role']
def features(df):
    X = pd.get_dummies(df[CATS].astype(str), prefix_sep='=')
    X['log_employees'] = np.log1p(df.employee_count)
    X['log_sites'] = np.log1p(df.num_sites)
    X['log_spend'] = np.log1p(df.monthly_telecom_spend_inr)
    X['n_interest'] = df.products_of_interest.fillna('').str.count(';') + 1
    return X
X = features(leads)
m = LogisticRegression(max_iter=4000, C=0.5).fit(X, y)
p = m.predict_proba(X)[:, 1]
print('in-sample AUC', round(roc_auc_score(y, p), 3))
model = dict(intercept=float(m.intercept_[0]), coef={c: round(float(v), 5) for c, v in zip(X.columns, m.coef_[0])}, cats=CATS,
             note='Logistic regression, scikit-learn, C=0.5. Hold-out AUC 0.75 (70/30 stratified split).')
js('propensity_model.js', 'PROPENSITY_MODEL', model)

# ---- back-office queue: leads that stalled after first contact (stand-in for leads the advisor could not close)
leads['score'] = p
q = leads[(leads.outcome == 'Dropped') & leads.stage_reached.isin(['Contacted', 'Needs assessed', 'Quote accepted', 'KYC complete'])].copy()
def mask_name(n):
    parts = str(n).split()
    return parts[0] + (' ' + parts[-1][0] + '.' if len(parts) > 1 else '')
rows = []
for r in q.itertuples():
    rows.append([r.lead_id, r.business_name, r.business_type, r.segment, r.city, int(r.city_tier), r.preferred_language, r.lead_source,
                 r.stage_reached, r.drop_reason, int(r.employee_count), int(r.num_sites), r.has_gstin, mask_name(r.contact_name), r.contact_role,
                 int(r.monthly_telecom_spend_inr), str(r.products_of_interest), round(float(r.score), 4), r.created_date])
js('leads_queue.js', 'LEADS_QUEUE', dict(columns=['id', 'business', 'type', 'segment', 'city', 'tier', 'language', 'source', 'stage', 'dropReason', 'employees', 'sites', 'hasGstin', 'contact', 'role', 'spend', 'interest', 'score', 'created'], rows=rows))

# ---- funnel baseline for the console header
act = leads[leads.outcome == 'Activated']
base = dict(leads=len(leads), activated=len(act), conversion=round(len(act) / len(leads), 4), daysToActivate=round(act.days_lead_to_activation.mean(), 1),
            followUps=round(act.customer_follow_up_calls.mean(), 1), cac=round(leads.acquisition_cost_inr.sum() / len(act)),
            churn=round((act.churned_within_6_months == 'Y').mean(), 3))
js('baseline.js', 'BASELINE', base)
